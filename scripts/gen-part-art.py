#!/usr/bin/env python3
"""Generate the breakout-module artwork in public/parts/.

Secure-element modules are drawn from geometric primitives: a PCB, the
device package at its real outline (SOIC-8, SOIC-14, QFN/HX2QFN), a
decoupling capacitor and a header row matching the catalog terminals
(src/project/catalog.ts). Markings are part numbers only; no vendor logos.

World units are 0.1 mm, as for the board artwork: one header pitch is 25.4.
Each SVG covers the module body above the header row; the canvas draws pin
labels and leads itself.

Usage: scripts/gen-part-art.py   (writes public/parts/*.svg)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public" / "parts"
P = 25.4
H = 5 * P  # module height above the header

SPI_PINS = ["VCC", "GND", "CS", "SCK", "MOSI", "MISO"]
I2C_PINS = ["VCC", "GND", "SCL", "SDA"]

# kind: (marking, second line, package, pins, PCB colour)
MODULES = {
    "se-atecc608": ("ATECC608A", "SPI · P-256", "soic8", SPI_PINS, "#5b2a86"),
    "se-ta100": ("TA100", "SPI · trust anchor", "soic14", SPI_PINS, "#7a1f3d"),
    "se-tropic01": ("TROPIC01", "SPI · Ed25519/X25519", "qfn32", SPI_PINS, "#14505c"),
    "se-se050": ("SE050", "I²C 0x48", "hx2qfn20", I2C_PINS, "#1f5f3a"),
    "se-stsafe": ("STSAFE-A120", "I²C 0x20", "so8n", I2C_PINS, "#1d3f7a"),
}


def soic(cx, cy, pins, body_w, body_l, pitch=12.7):
    """Gull-wing SOIC: leads on the long sides, pin-1 dot."""
    per = pins // 2
    span = (per - 1) * pitch
    parts = []
    for i in range(per):
        x = cx - span / 2 + i * pitch
        for side in (-1, 1):
            y = cy + side * (body_w / 2 + 5)
            parts.append(f'<rect x="{x - 2.2:.1f}" y="{y - 5:.1f}" width="4.4" height="10" fill="#c9c9c9" stroke="#8a8a8a" stroke-width="0.5"/>')
    parts.append(f'<rect x="{cx - body_l / 2:.1f}" y="{cy - body_w / 2:.1f}" width="{body_l:.1f}" height="{body_w:.1f}" rx="2" fill="#1b1b1d" stroke="#000" stroke-width="0.8"/>')
    parts.append(f'<circle cx="{cx - body_l / 2 + 5:.1f}" cy="{cy + body_w / 2 - 5:.1f}" r="1.8" fill="#4a4a4f"/>')
    return parts


def qfn(cx, cy, size, per_side, pitch):
    """QFN: pads on four sides, exposed thermal pad, pin-1 chamfer."""
    s = size / 2
    span = (per_side - 1) * pitch
    parts = [f'<rect x="{cx - s:.1f}" y="{cy - s:.1f}" width="{size:.1f}" height="{size:.1f}" rx="1.5" fill="#1b1b1d" stroke="#000" stroke-width="0.8"/>']
    for i in range(per_side):
        o = -span / 2 + i * pitch
        for (x, y, w, h) in ((cx + o - 1, cy + s - 2.5, 2, 3.5), (cx + o - 1, cy - s - 1, 2, 3.5),
                             (cx - s - 1, cy + o - 1, 3.5, 2), (cx + s - 2.5, cy + o - 1, 3.5, 2)):
            parts.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" fill="#bdbdbd"/>')
    parts.append(f'<path d="M {cx - s:.1f} {cy - s + 5:.1f} L {cx - s + 5:.1f} {cy - s:.1f}" stroke="#4a4a4f" stroke-width="1.2"/>')
    return parts


def padlock(x, y, colour):
    return [
        f'<path d="M {x - 4} {y} v -4 a 4 4 0 0 1 8 0 v 4" fill="none" stroke="{colour}" stroke-width="1.6"/>',
        f'<rect x="{x - 6}" y="{y}" width="12" height="9" rx="1.5" fill="{colour}"/>',
        f'<circle cx="{x}" cy="{y + 4}" r="1.4" fill="#111"/>',
    ]


def module_svg(kind, marking, sub, package, pins, colour):
    w = len(pins) * P
    cx, cy = w / 2, H * 0.44
    body = []
    body_w = {"soic8": 49, "so8n": 49, "soic14": 86.5, "qfn32": 40, "hx2qfn20": 30}[package]
    if package == "soic8":
        body += soic(cx, cy, 8, 39, 49)
    elif package == "so8n":
        body += soic(cx, cy, 8, 39, 49)
    elif package == "soic14":
        body += soic(cx, cy, 14, 39, 86.5)
    elif package == "qfn32":
        body += qfn(cx, cy, 40, 8, 4)
    elif package == "hx2qfn20":
        body += qfn(cx, cy, 30, 5, 5)
    label_y = cy + 2.5
    # Monospace glyphs are about 0.6 em wide; keep the marking on the body.
    fs = min(7.5, 0.85 * body_w / (0.6 * len(marking)))
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.1f} {H:.1f}" width="{w:.1f}" height="{H:.1f}">',
        f'<!-- m33mu-lab {kind} breakout: original illustration, CC0-1.0 (generated by scripts/gen-part-art.py). -->',
        f'<rect x="0.8" y="0.8" width="{w - 1.6:.1f}" height="{H - 1.6:.1f}" rx="6" fill="{colour}" stroke="#0b0b0b" stroke-width="1.6"/>',
        f'<rect x="5" y="5" width="{w - 10:.1f}" height="{H - 10:.1f}" rx="3" fill="none" stroke="#f2f2f2" stroke-opacity="0.55" stroke-width="0.8"/>',
    ]
    for (hx, hy) in ((11, 11), (w - 11, 11)):
        out.append(f'<circle cx="{hx:.1f}" cy="{hy:.1f}" r="5" fill="#d6b45c"/><circle cx="{hx:.1f}" cy="{hy:.1f}" r="3" fill="#2b2b2b"/>')
    # Decoupling capacitor (0603) beside the package, with its trace to VCC.
    out.append(f'<rect x="{w - 20:.1f}" y="{cy - 4:.1f}" width="8" height="5" fill="#c49a6c" stroke="#6b4b2a" stroke-width="0.5"/>')
    out.append(f'<path d="M {P / 2:.1f} {H - 2:.1f} V {cy + 18:.1f} H {w - 16:.1f} V {cy + 1:.1f}" fill="none" stroke="#ffffff" stroke-opacity="0.18" stroke-width="2"/>')
    out += body
    out.append(f'<text x="{cx:.1f}" y="{label_y:.1f}" font-family="DejaVu Sans Mono, monospace" font-size="{fs:.1f}" fill="#e8e8e8" text-anchor="middle">{marking}</text>')
    out += padlock(14, H * 0.62, "#f4d35e")
    out.append(f'<text x="{cx:.1f}" y="{H - 22:.1f}" font-family="DejaVu Sans, sans-serif" font-size="8" fill="#ffffff" text-anchor="middle">{sub}</text>')
    # Header pads at the bottom edge, one per catalog terminal.
    for i in range(len(pins)):
        x = P / 2 + i * P
        out.append(f'<rect x="{x - 6:.1f}" y="{H - 13:.1f}" width="12" height="12" rx="2" fill="#d6b45c" stroke="#8c7230" stroke-width="0.8"/>')
        out.append(f'<circle cx="{x:.1f}" cy="{H - 7:.1f}" r="3.2" fill="#2b2b2b"/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for kind, (marking, sub, package, pins, colour) in MODULES.items():
        (OUT / f"{kind}.svg").write_text(module_svg(kind, marking, sub, package, pins, colour), encoding="utf-8")
    print(f"wrote {len(MODULES)} module drawings to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
