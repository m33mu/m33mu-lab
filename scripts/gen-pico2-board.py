#!/usr/bin/env python3
"""Electrical map of the Raspberry Pi Pico 2 header (rp2350 board).

Evidence: Raspberry Pi Pico 2 Datasheet, Figure 2 "The pinout of the
Raspberry Pi Pico 2 board" (pins 1-40, GPn/GND/power labels) and section 3.1
(PIN30 RUN, PIN33 AGND, PIN35 ADC_VREF, PIN36 3V3, PIN37 3V3_EN, PIN39 VSYS,
PIN40 VBUS; GPIO25 drives the user LED; GPIO23/24/29 are internal). The
sprite pack's J_LEFT/J_RIGHT signal names match that figure pin for pin.

GPn contacts become the RP2350 pad GPIOn; GND and AGND are board ground;
3V3(OUT) is the 3.3 V rail (an ideal source on the bench). VBUS, VSYS,
3V3_EN, ADC_VREF and RUN are not modelled and stay visual-only, as do the
SWD pads.

Usage: scripts/gen-pico2-board.py   (rewrites public/boards/layout/rp2350.json
and boards/pico2-pins.json)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAYOUT = ROOT / "public" / "boards" / "layout" / "rp2350.json"
PINS = ROOT / "boards" / "pico2-pins.json"

DATASHEET = "https://datasheets.raspberrypi.com/pico/pico-2-datasheet.pdf"
NOT_MODELLED = {
    "VBUS": "VBUS (USB 5 V input): not modelled on the bench",
    "VSYS": "VSYS (system input to the SMPS): not modelled on the bench",
    "3V3_EN": "3V3_EN (SMPS enable): not modelled on the bench",
    "ADC_VREF": "ADC_VREF: the ADC is not modelled",
    "RUN": "RUN (RP2350 reset): not modelled on the bench",
}
GROUND = {"GND", "AGND"}
# Pin 36 is labelled 3V3(OUT) in Figure 2 and 3V3 in section 3.1.
RAIL = {"3V3": "3V3"}


def net_for(signal):
    if signal is None:
        return None, "SWD debug pad: not modelled on the bench"
    if signal.startswith("GP") and signal[2:].isdigit():
        return f"GPIO{int(signal[2:])}", None
    if signal in GROUND:
        return "GND", None
    if signal in RAIL:
        return RAIL[signal], None
    return None, NOT_MODELLED.get(signal, f"{signal}: not modelled on the bench")


def main():
    layout = json.loads(LAYOUT.read_text(encoding="utf-8"))
    contacts = []
    for conn in layout["connectors"]:
        for c in conn["contacts"]:
            net, why = net_for(c.get("signal"))
            for key in ("net", "socPad", "electricalEnabled", "note"):
                c.pop(key, None)
            if net:
                c["socPad"] = net
                c["electricalEnabled"] = True
            else:
                c["electricalEnabled"] = False
                c["note"] = why
            contacts.append({
                "connectorId": conn["id"], "physicalPadNumber": c["number"],
                "signal": c.get("signal"), "net": net,
                "signalMappingVerified": c.get("signal") is not None,
                "electricalEnabled": net is not None,
                **({"note": why} if why else {}),
            })
    layout["electricalMapStatus"] = "verified_pico2_datasheet_figure2"
    layout["electricalEnabledByDefault"] = False
    layout["leds"] = [{"id": "LED", "pad": "GPIO25", "color": "#2fb34a",
                       "x": 274, "y": 139, "w": 12, "h": 8, "activeHigh": True}]
    LAYOUT.write_text(json.dumps(layout, indent=2) + "\n", encoding="utf-8")
    PINS.write_text(json.dumps({
        "schemaVersion": 1, "boardId": "raspberry-pi-pico-2", "cpu": "rp2350",
        "boardRevision": "Raspberry Pi Pico 2 (RP2350A); datasheet build 2025",
        "electricalMapStatus": "verified",
        "sources": [{
            "kind": "manufacturer-datasheet-figure", "url": DATASHEET,
            "revision": "Raspberry Pi Pico 2 Datasheet, Figure 2 (p.5) and section 3.1 (pp.7-8)",
            "evidence": "Figure 2 labels pins 1-40: GP0..GP15 on pins 1-20 with GND on 3/8/13/18, "
                        "GP16..GP22 on 21-29 with GND on 23/28, RUN 30, GP26 31, GP27 32, AGND 33, GP28 34, "
                        "ADC_VREF 35, 3V3(OUT) 36, 3V3_EN 37, GND 38, VSYS 39, VBUS 40, LED on GP25. "
                        "Section 3.1 lists the non-GPIO pins and GPIO23/24/25/29 internal uses."}],
        "review": {"reviewer": "Claude (m33mu-lab session)", "reviewedAt": "2026-10-24",
                   "note": "Contact positions are the sprite pack's stylized hit-test anchors; signal identity "
                           "per pin is from the datasheet figure. Generated by scripts/gen-pico2-board.py."},
        "contacts": contacts,
    }, indent=2) + "\n", encoding="utf-8")
    enabled = sum(1 for c in contacts if c["electricalEnabled"])
    print(f"Pico 2: {enabled} of {len(contacts)} contacts electrical")


if __name__ == "__main__":
    main()
