#!/usr/bin/env python3
"""Generate sim/stm32-af.ts: the bus alternate functions of each STM32 board.

Source: ST's pin data as published in Zephyr's hal_stm32 module
(dts/st/<series>/<part>-pinctrl.dtsi, Apache-2.0, generated by ST's
genpinctrl.py from STM32 Open Pin Data). Pass the hal_stm32 checkout:

  scripts/gen-stm32-af.py <hal_stm32>/dts/st > sim/stm32-af.ts
"""
import re
import sys
from pathlib import Path

# m33mu CPU -> the package on its board.
PARTS = {
    "stm32h563": "h5/stm32h563zitx-pinctrl.dtsi",       # NUCLEO-H563ZI
    "stm32h533": "h5/stm32h533retx-pinctrl.dtsi",       # NUCLEO-H533RE
    "stm32u585": "u5/stm32u585zitxq-pinctrl.dtsi",      # NUCLEO-U575ZI-Q footprint
    "stm32l552": "l5/stm32l552z(c-e)txq-pinctrl.dtsi",  # NUCLEO-L552ZE-Q
    "stm32n657": "n6/stm32n657x0hxq-pinctrl.dtsi",      # NUCLEO-N657X0-Q
}

NODE = re.compile(
    r"/omit-if-no-ref/\s+(\w+):\s*\w+\s*\{\s*pinmux\s*=\s*<STM32_PINMUX\('([A-Z])',\s*(\d+),\s*AF(\d+)\)>",
)
SIGNAL = re.compile(r"^((?:spi|i2c|usart|uart|lpuart)\d+)_(sck|miso|mosi|scl|sda|tx|rx)_p[a-z]\d+$")


TIMER = re.compile(r"^(tim[2-5])_(ch[1-4])_p[a-z]\d+$")


def table(path: Path, signal=SIGNAL) -> dict:
    out: dict = {}
    for name, port, pin, af in NODE.findall(path.read_text()):
        m = signal.match(name)
        if not m:
            continue
        pad = f"P{port}{int(pin)}"
        out.setdefault(pad, {})[int(af)] = f"{m.group(1).upper()}_{m.group(2).upper()}"
    return out


def pad_key(pad: str):
    return (pad[1], int(pad[2:]))


def main() -> None:
    root = Path(sys.argv[1])
    print("// Generated by scripts/gen-stm32-af.py from ST pin data in Zephyr")
    print("// hal_stm32 (dts/st/*-pinctrl.dtsi, Apache-2.0). Do not edit.")
    print("//")
    print()
    emit("STM32_AF", "SPI/I2C/U(S)ART", root, SIGNAL)
    print()
    emit("STM32_TIM_AF", "TIM2-TIM5 channel (the timers m33mu drives onto pads)", root, TIMER, TIMER_CPUS)


# CPUs whose m33mu model drives TIM2-TIM5 outputs onto pads (no N657 timers).
TIMER_CPUS = {"stm32h563", "stm32h533", "stm32u585", "stm32l552"}


def emit(const: str, what: str, root: Path, signal, cpus=None) -> None:
    print(f"/** {what} alternate functions: cpu -> pad -> AF -> signal. */")
    print(f"export const {const}: Record<string, Record<string, Record<number, string>>> = {{")
    for cpu, rel in PARTS.items():
        if cpus is not None and cpu not in cpus:
            continue
        t = table(root / rel, signal)
        print(f"  // {Path(rel).name.removesuffix('-pinctrl.dtsi').upper()}")
        print(f"  {cpu}: {{")
        for pad in sorted(t, key=pad_key):
            afs = ", ".join(f"{af}: '{sig}'" for af, sig in sorted(t[pad].items()))
            print(f"    {pad}: {{ {afs} }},")
        print("  },")
    print("};")

if __name__ == "__main__":
    main()
